#!/usr/bin/env python3
"""
Emit three TikZ radar (spider) charts for RQ2: per-reporting-group SK
0-shot scores of three Slovak base checkpoints, before (base) and after
(+Alpaca) a small Slovak instruction-tuning step. Where the upstream
non-Slovak model was also evaluated (Qwen3-SK), its released checkpoint
is shown as a third polygon, giving the full original -> Slovak
pretraining -> +Alpaca trajectory. Reuses the reporting-group / metric
definitions from fewshot_compare.py. No deps.

Usage: python scripts/make_adaptation_radar.py --out <path/fig_adaptation.tex>
"""
from __future__ import annotations
import argparse, json, os
from statistics import mean
import importlib.util

spec = importlib.util.spec_from_file_location(
    "fs", os.path.join(os.path.dirname(__file__), "fewshot_compare.py"))
fs = importlib.util.module_from_spec(spec); spec.loader.exec_module(fs)

AGG = "final_results/outputs/aggregated"
AXES = [("Know.", "Knowledge & Reasoning"), ("Read.", "Reading & QA"),
        ("Class.", "Classification"), ("Gen.", "Generation"),
        ("Instr.", "Instruction"), ("Gram.", "Grammar & Morphology")]
ANGLES = [90, 30, -30, -90, -150, 150]
# (display name, original|None, Slovak base/CPT, +Alpaca)
PAIRS = [("Mistral-SK 7B", None, "slovak-nlp__mistral-sk-7b",
          "mrshu__mistral-sk-7b-alpaca-slovak-it"),
         ("TildeOpen-SK 30B", None, "TildeAI__TildeOpen-30b-64k",
          "mrshu__tildeopen-30b-64k-sk-alpaca-slovak-it"),
         ("Qwen3-SK 14B", "Qwen__Qwen3-14B", "slovak-nlp__Qwen3-14B-sk",
          "mrshu__qwen3-14b-sk-alpaca-slovak-it")]
R = 1.35
DX = 4.6
ORIG = "draw=black!55,densely dashed,line width=0.7pt"
BASE = "draw=promptframe,line width=0.8pt,fill=promptframe,fill opacity=0.18"
TUNED = "draw=newgold,line width=0.9pt,fill=newgold,fill opacity=0.30"


def group_scores(stem):
    r = json.load(open(f"{AGG}/{stem}.json"))["results"]
    out = []
    for _, theme in AXES:
        vals = [fs.task_val(r, k, "SK", 0) for k, t in fs.TASK_GROUPS if t == theme]
        vals = [v for v in vals if v is not None]
        out.append(100 * mean(vals) if vals else 0.0)
    return out


def polygon(vals, style):
    pts = " -- ".join(f"({a}:{v/100*R:.3f}cm)" for a, v in zip(ANGLES, vals))
    return f"\\draw[{style}] {pts} -- cycle;"


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--out", required=True)
    out = ap.parse_args().out
    L = [r"% Auto-generated by sk-bench/scripts/make_adaptation_radar.py",
         r"\begin{figure*}[t]", r"\centering",
         r"\resizebox{0.92\textwidth}{!}{%", r"\begin{tikzpicture}"]
    for i, (name, orig, base, tuned) in enumerate(PAIRS):
        cx = i * DX
        L.append(f"\\begin{{scope}}[shift={{({cx}cm,0)}}]")
        for rr in (0.25, 0.5, 0.75, 1.0):
            ring = " -- ".join(f"({a}:{rr*R:.3f}cm)" for a in ANGLES)
            L.append(f"  \\draw[gray!30,line width=0.3pt] {ring} -- cycle;")
        for a in ANGLES:
            L.append(f"  \\draw[gray!30,line width=0.3pt] (0,0) -- ({a}:{R}cm);")
        for (lab, _), a in zip(AXES, ANGLES):
            L.append(f"  \\node[font=\\scriptsize] at ({a}:{R+0.42}cm) {{{lab}}};")
        if orig:                                  # original behind, no fill
            L.append("  " + polygon(group_scores(orig), ORIG))
        L.append("  " + polygon(group_scores(base), BASE))
        L.append("  " + polygon(group_scores(tuned), TUNED))
        L.append(f"  \\node[font=\\small,below] at (0,-{R+0.7}cm) {{{name}}};")
        L.append(r"\end{scope}")
    # legend, centred under the middle radar
    L += [
        f"\\begin{{scope}}[shift={{({DX}cm,-{R+1.4}cm)}}]",
        r"  \draw[" + ORIG + r"] (-2.75,0.11) -- (-2.35,0.11);",
        r"  \node[font=\scriptsize,anchor=west] at (-2.30,0.11) {original (Qwen only)};",
        r"  \draw[" + BASE + r"] (0.30,0) rectangle (0.60,0.22);",
        r"  \node[font=\scriptsize,anchor=west] at (0.65,0.11) {Slovak base};",
        r"  \draw[" + TUNED + r"] (2.25,0) rectangle (2.55,0.22);",
        r"  \node[font=\scriptsize,anchor=west] at (2.60,0.11) {$+$\,Alpaca};",
        r"\end{scope}",
    ]
    L += [r"\end{tikzpicture}%", r"}",
          r"\caption{RQ2: per-reporting-group scores (Slovak, 0-shot, axes "
          r"$0$--$100$) of three Slovak base checkpoints before (Slovak base) "
          r"and after ($+$Alpaca) a small Slovak instruction-tuning step. For "
          r"Qwen3-SK, whose upstream multilingual model (Qwen3-14B) was also "
          r"evaluated, the dashed polygon shows that released model before "
          r"Slovak adaptation; the upstream bases of Mistral-SK and "
          r"TildeOpen-SK are not in the sweep. The effect varies by base and "
          r"by group: Alpaca broadly lifts Qwen3-SK (knowledge, reading, "
          r"classification, instruction-following) at the cost of grammar, is "
          r"mixed for TildeOpen-SK, and mostly shrinks the weakest "
          r"(Mistral-SK); and Slovak adaptation itself drops Qwen3-14B before "
          r"Alpaca partly restores it (\S\ref{sec:rq2}; per-group deltas in "
          r"Table~\ref{tab:alpaca-delta}).}",
          r"\label{fig:adaptation}", r"\end{figure*}", ""]
    open(out, "w").write("\n".join(L))
    print(f"wrote {out}")
    for name, orig, base, tuned in PAIRS:
        line = f"  {name}: base={[round(x) for x in group_scores(base)]} " \
               f"+Alpaca={[round(x) for x in group_scores(tuned)]}"
        if orig:
            line += f" orig={[round(x) for x in group_scores(orig)]}"
        print(line)


if __name__ == "__main__":
    main()
