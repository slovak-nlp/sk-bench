#!/usr/bin/env python3
"""
Emit a pgfplots scatter figure (LaTeX) for the RQ1 provenance contrasts.

For each matched contrast it plots all evaluated models as a point
(native score x, translated/generated score y) against the y=x diagonal,
so the reader sees directly where translation/generation preserves the
ranking (points on the diagonal) and where it does not (points off it).

Reads the per-model aggregated JSONs and writes a self-contained
tikzpicture to <out>. No third-party deps (stdlib only).

Usage:
    python scripts/make_provenance_scatter.py \
        --agg final_results/outputs/aggregated \
        --out /path/to/latex/figures/provenance_scatter.tex
"""
from __future__ import annotations
import argparse, glob, json, os

CONTRASTS = [
    ("NLI", "nli_sk_SK_AVERAGE|0", "acc", "sklep_nli_SK_AVERAGE|0", "acc",
     "native NLI", "translated NLI", r"$\rho=0.99$"),
    ("Multiple choice", "e_tests_mqa_SK_AVERAGE|0", "acc", "mmlu_SK_AVERAGE|0", "acc",
     "native exams", "translated MMLU", r"$\rho=0.98$"),
    ("QA", "sklep_qa_SK_AVERAGE|0", "qem", "multi_wiki_qa_SK_AVERAGE|0", "qem",
     "human SK-QuAD", "generated WikiQA", r"$\rho=0.72$"),
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--agg", default="final_results/outputs/aggregated")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    results = []
    for f in sorted(glob.glob(f"{args.agg}/*.json")):
        results.append(json.load(open(f))["results"])

    panels = []
    for name, kx, mx, ky, my, xlab, ylab, rho in CONTRASTS:
        pts = []
        for r in results:
            vx, vy = r.get(kx), r.get(ky)
            if not vx or not vy:
                continue
            x, y = vx.get(mx), vy.get(my)
            if x is None or y is None:
                continue
            pts.append((100 * x, 100 * y))
        coords = " ".join(f"({x:.1f},{y:.1f})" for x, y in pts)
        panels.append((name, xlab, ylab, rho, coords, len(pts)))

    lines = [
        r"% Auto-generated by sk-bench/scripts/make_provenance_scatter.py",
        r"\begin{figure*}[t]",
        r"\centering",
        r"\resizebox{\textwidth}{!}{%",
        r"\begin{tikzpicture}",
        r"\begin{groupplot}[",
        r"  group style={group size=3 by 1, horizontal sep=1.6cm},",
        r"  width=0.30\textwidth, height=0.22\textwidth,",
        r"  xmin=0, xmax=100, ymin=0, ymax=100,",
        r"  xtick={0,50,100}, ytick={0,50,100},",
        r"  tick label style={font=\scriptsize},",
        r"  title style={font=\footnotesize}, label style={font=\scriptsize},",
        r"  scatter/use mapped color={draw=promptframe, fill=promptframe},",
        r"]",
    ]
    for name, xlab, ylab, rho, coords, n in panels:
        lines += [
            f"\\nextgroupplot[title={{{name} ({rho})}}, xlabel={{{xlab}}}, ylabel={{{ylab}}}]",
            r"\addplot[domain=0:100, dashed, gray, thick, forget plot] {x};",
            r"\addplot[only marks, mark=*, mark size=0.8pt, "
            r"draw=promptframe, fill=promptframe, fill opacity=0.55] coordinates {",
            f"  {coords}",
            r"};",
        ]
    lines += [
        r"\end{groupplot}",
        r"\end{tikzpicture}%",
        r"}",
        r"\caption{RQ1 data-provenance contrasts: each point is one of the "
        r"55 models, scored on the native source ($x$) and its "
        r"translated or LLM-generated counterpart ($y$); the dashed line is "
        r"$y=x$. Points hug the diagonal for NLI and multiple choice "
        r"(translation preserves the ranking) but scatter off it for QA "
        r"(human-authored vs.\ generated questions disagree), concentrated "
        r"among weaker models. Per-tier $\rho$ and top-10 overlap are in "
        r"Table~\ref{tab:provenance-divergence}.}",
        r"\label{fig:provenance-scatter}",
        r"\end{figure*}",
        "",
    ]
    with open(args.out, "w") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {args.out}; panels: " + ", ".join(f"{p[0]}({p[5]})" for p in panels))


if __name__ == "__main__":
    main()
